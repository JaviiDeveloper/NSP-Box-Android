package com.nspbox.domain.keys

import java.io.File
import java.security.MessageDigest

object PlaceholderKeys {

    private val PLACEHOLDERS = mapOf(
        "header_key" to sha256Hex("local-plaintext-xci-header-placeholder"),
        "key_area_key_application_00" to md5Hex("local-plaintext-xci-area-placeholder")
    )

    fun placeholderText(names: Set<String>? = null): String {
        val selected = if (names != null) PLACEHOLDERS.filterKeys { it in names } else PLACEHOLDERS
        return buildString {
            appendLine("# Local placeholders for unsigned plaintext repacks; NOT Nintendo keys.")
            appendLine("# Cannot decrypt retail content. Keep real keys in prod.keys.")
            for ((name, value) in selected) {
                appendLine("$name = $value")
            }
        }
    }

    fun inspect(directory: File): Map<String, Any?> {
        val effective = mutableMapOf<String, String>()

        for (filename in listOf("prod.keys_autogenerated", "prod.keys")) {
            val file = File(directory, filename)
            if (!file.exists()) continue
            require(file.length() <= 8 * 1024 * 1024) { "Key configuration file is unexpectedly large." }

            for (line in file.readText(Charsets.UTF_8).lines()) {
                if (line.trimStart().startsWith("#") || '=' !in line) continue
                val (name, value) = line.split("=", limit = 2)
                val key = name.trim().lowercase()
                if (key in PLACEHOLDERS) {
                    effective[key] = value.trim()
                }
            }
        }

        val missing = PLACEHOLDERS.keys.filter { it !in effective }
        val invalid = effective.filter { (k, v) ->
            !v.matches(Regex("[0-9a-fA-F]{${PLACEHOLDERS[k]!!.length}}"))
        }.keys.toList()

        return mapOf(
            "ready" to (missing.isEmpty() && invalid.isEmpty()),
            "missing" to missing,
            "invalid" to invalid
        )
    }

    fun install(directory: File): Map<String, Any?> {
        directory.mkdirs()
        val status = inspect(directory)
        @Suppress("UNCHECKED_CAST")
        val invalid = status["invalid"] as List<String>
        require(invalid.isEmpty()) {
            "Existing entries need manual correction: ${invalid.joinToString(", ")}"
        }
        if (status["ready"] == true) {
            return status + mapOf("added" to emptyList<String>(), "backup" to null)
        }

        @Suppress("UNCHECKED_CAST")
        val missing = status["missing"] as List<String>
        val target = File(directory, "prod.keys_autogenerated")
        val before = if (target.exists()) target.readBytes() else null
        val addition = placeholderText(missing.toSet()).toByteArray(Charsets.UTF_8)
        val separator = if (before != null && !before.last().toInt().toChar().let { it == '\n' }) "\n".toByteArray() else byteArrayOf()
        val content = (before ?: byteArrayOf()) + separator + addition

        var backup: File? = null
        if (before == null) {
            target.writeBytes(content)
        } else {
            val timestamp = java.text.SimpleDateFormat("yyyyMMdd-HHmmss-SSS", java.util.Locale.US)
                .format(java.util.Date())
            backup = File(directory, "${target.name}.packager-backup-$timestamp")
            backup.writeBytes(before)
            target.writeBytes(content)
        }

        return inspect(directory) + mapOf(
            "added" to missing,
            "backup" to backup?.absolutePath
        )
    }

    private fun sha256Hex(input: String): String {
        return MessageDigest.getInstance("SHA-256")
            .digest(input.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
    }

    private fun md5Hex(input: String): String {
        return MessageDigest.getInstance("MD5")
            .digest(input.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
    }
}
